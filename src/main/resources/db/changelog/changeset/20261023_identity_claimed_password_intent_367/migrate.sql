CREATE TABLE identity_claimed_password_intent (
  claim_id VARCHAR(36) NOT NULL,
  claim_version BIGINT NOT NULL,
  operation_id VARCHAR(36) NOT NULL,
  workflow_kind VARCHAR(32) NOT NULL,
  realm_id VARCHAR(512) NOT NULL,
  account_id VARCHAR(36) NOT NULL,
  tenant_id BIGINT NULL,
  owner_client VARCHAR(255) NOT NULL,
  owner_subject VARCHAR(36) NOT NULL,
  request_digest CHAR(64) NOT NULL,
  authority_valid_until BIGINT NOT NULL,
  target_json LONGTEXT NOT NULL,
  workflow_json LONGTEXT NULL,
  local_state_json LONGTEXT NOT NULL,
  metadata_json LONGTEXT NULL,
  intent_envelope LONGTEXT NULL,
  intent_digest CHAR(64) NULL,
  status VARCHAR(32) NOT NULL,
  receipt LONGTEXT NULL,
  updated_at DATETIME(6) NOT NULL,
  PRIMARY KEY (claim_id, claim_version),
  UNIQUE KEY uq_identity_claimed_password_operation (operation_id),
  INDEX idx_identity_claimed_password_account (account_id, status),
  INDEX idx_identity_claimed_password_expiry (authority_valid_until, claim_id, claim_version)
);
