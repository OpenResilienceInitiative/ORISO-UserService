  @Test
  void failedCreationCleanupDeletesOnlyMatchingUnprogressedSnapshot() {
    var service = createService(new Effects());
    var captured = Instant.parse("2026-01-01T00:00:00.123456Z");
    service.assignAtCreation("failed", 1L, 24, 7, captured);
    assertThat(service.discardUncompletedCreation("failed", 12, 7, captured)).isFalse();
    assertThat(service.discardUncompletedCreation("failed", 24, 8, captured)).isFalse();
    assertThat(service.discardUncompletedCreation("failed", 24, 7, captured.plusSeconds(1)))
        .isFalse();
    assertThat(service.discardUncompletedCreation("failed", 24, 7, captured)).isTrue();
    assertThat(service.snapshot("failed")).isEmpty();
    assertThat(service.discardUncompletedCreation("failed", 24, 7, captured)).isFalse();
    service.assignAtCreation("active", 1L, 24, 7, captured);
    service.recordActivity("active", captured.plusSeconds(1));
    assertThat(service.discardUncompletedCreation("active", 24, 7, captured)).isFalse();
    service.assignAtCreation("suspended", 1L, 24, 7, captured);
    service.suspend("suspended");
    assertThat(service.discardUncompletedCreation("suspended", 24, 7, captured)).isFalse();
    service.reactivate("suspended");
    assertThat(service.discardUncompletedCreation("suspended", 24, 7, captured)).isFalse();
  }

  @Test
  void creationSnapshotSurvivesChangedDefaultsAndUsesCalendarMonths() {
    var ds = new DriverManagerDataSource("jdbc:h2:mem:inactivity;DB_CLOSE_DELAY=-1", "sa", "");
    var jdbc = new JdbcTemplate(ds);
    jdbc.execute("DROP TABLE IF EXISTS account_inactivity");
    jdbc.execute("DROP TABLE IF EXISTS account_inactivity_journal");
    jdbc.execute(
        "CREATE TABLE account_inactivity_journal(journal_id BIGINT GENERATED BY DEFAULT AS IDENTITY"
            + " PRIMARY KEY,identity_id VARCHAR(36),action VARCHAR(30),target VARCHAR(30),outcome"
            + " VARCHAR(40),created_at TIMESTAMP(6))");
    jdbc.execute(
        "CREATE TABLE account_inactivity(identity_id VARCHAR(36) PRIMARY KEY,tenant_id"
            + " BIGINT,assigned_months INT NOT NULL,revision BIGINT NOT NULL,last_activity"
            + " TIMESTAMP(6) NOT NULL,due_at TIMESTAMP(6) NOT NULL,status VARCHAR(20) NOT"
            + " NULL,last_error VARCHAR(1000),attempts INT DEFAULT 0 NOT NULL)");
    var service =
        new AccountInactivityService(
            jdbc,
            new DataSourceTransactionManager(ds),
            Clock.fixed(Instant.parse("2026-02-15T12:00:00Z"), ZoneOffset.UTC),
            new Effects());
    service.assignAtCreation("person", 1L, 1, 1, Instant.parse("2026-01-31T12:00:00Z"));
    service.assignAtCreation("person", 1L, 24, 2, Instant.parse("2026-02-01T12:00:00Z"));
    var snapshot = service.snapshot("person").orElseThrow();
    assertThat(snapshot.assignedMonths()).isEqualTo(1);
    assertThat(snapshot.dueAt()).isEqualTo(Instant.parse("2026-02-28T12:00:00Z"));
    service.recordActivity("person", Instant.parse("2026-02-15T10:00:00Z"));
    assertThat(service.snapshot("person").orElseThrow().dueAt())
        .isEqualTo(Instant.parse("2026-03-15T10:00:00Z"));
  }

