  @Test
  void candidateReportShowsCurrentRoleActionAndIsolatesRoleLookupFailure() {
    var service =
        createService(
            new Effects() {
              public Set<Role> currentRoles(String id) {
                if (id.equals("a")) return Set.of(Role.ASKER);
                if (id.equals("b")) return Set.of(Role.ASKER, Role.CONSULTANT);
                throw new IllegalStateException("Remote unavailable");
              }
            });
    for (var id : java.util.List.of("a", "b", "c"))
      service.assignAtCreation(id, 1L, 1, 1, Instant.parse("2026-01-01T00:00:00Z"));
    assertThat(
            service.candidateReport("", 3).stream()
                .map(AccountInactivityService.Candidate::plannedAction))
        .containsExactly(
            AccountInactivityService.PlannedAction.DELETE,
            AccountInactivityService.PlannedAction.SUSPEND,
            AccountInactivityService.PlannedAction.BLOCKED);
    assertThat(service.candidateReport("a", 1).getFirst().snapshot().identityId()).isEqualTo("b");
    assertThat(service.snapshot("a").orElseThrow().status())
        .isEqualTo(AccountInactivityService.Status.ACTIVE);
  }

  @Test
  void durableClaimSurvivesAnOuterCallerRollback() {
    createService(new Effects());
    var ds = new DriverManagerDataSource("jdbc:h2:mem:lifecycle;DB_CLOSE_DELAY=-1", "sa", "");
    var manager = new DataSourceTransactionManager(ds);
    var service =
        new AccountInactivityService(
            new JdbcTemplate(ds),
            manager,
            Clock.fixed(Instant.parse("2026-02-01T00:00:00Z"), ZoneOffset.UTC),
            new Effects() {
              public boolean suspend(String id) {
                return false;
              }
            });
    service.assignAtCreation("rollback", 1L, 24, 1, Instant.parse("2026-01-01T00:00:00Z"));
    var outer = new org.springframework.transaction.support.TransactionTemplate(manager);
    org.assertj.core.api.Assertions.assertThatThrownBy(
            () ->
                outer.executeWithoutResult(
                    ignored -> {
                      service.suspend("rollback");
                      throw new IllegalStateException("caller rollback");
                    }))
        .isInstanceOf(IllegalStateException.class);
    assertThat(service.snapshot("rollback").orElseThrow().status())
        .isEqualTo(AccountInactivityService.Status.SUSPENDING);
  }

