  @Test
  void concurrentScansPerformOneConfirmedEffect() throws Exception {
    var entered = new java.util.concurrent.CountDownLatch(1);
    var release = new java.util.concurrent.CountDownLatch(1);
    var actions = new java.util.concurrent.atomic.AtomicInteger();
    var service =
        createService(
            new Effects() {
              public boolean delete(String id) {
                actions.incrementAndGet();
                entered.countDown();
                try {
                  if (!release.await(10, java.util.concurrent.TimeUnit.SECONDS))
                    throw new IllegalStateException("Timed out");
                } catch (InterruptedException e) {
                  throw new RuntimeException(e);
                }
                return true;
              }
            });
    service.assignAtCreation("workers", 1L, 1, 1, Instant.parse("2026-01-01T00:00:00Z"));
    try (var pool = java.util.concurrent.Executors.newFixedThreadPool(2)) {
      var first = pool.submit(() -> service.scan(false));
      assertThat(entered.await(10, java.util.concurrent.TimeUnit.SECONDS)).isTrue();
      var second = pool.submit(() -> service.scan(false));
      release.countDown();
      first.get(10, java.util.concurrent.TimeUnit.SECONDS);
      second.get(10, java.util.concurrent.TimeUnit.SECONDS);
    }
    assertThat(actions.get()).isEqualTo(1);
    assertThat(service.snapshot("workers").orElseThrow().status())
        .isEqualTo(AccountInactivityService.Status.DELETED);
  }

  @Test
  void committedActivityWinsAgainstConcurrentExpiryClaim() throws Exception {
    var actions = new java.util.concurrent.atomic.AtomicInteger();
    var service =
        createService(
            new Effects() {
              public boolean delete(String id) {
                actions.incrementAndGet();
                return true;
              }
            });
    service.assignAtCreation("activity", 1L, 1, 1, Instant.parse("2026-01-01T00:00:00Z"));
    var ds = new DriverManagerDataSource("jdbc:h2:mem:lifecycle;DB_CLOSE_DELAY=-1", "sa", "");
    var template =
        new org.springframework.transaction.support.TransactionTemplate(
            new DataSourceTransactionManager(ds));
    var sameTransactionService =
        new AccountInactivityService(
            new JdbcTemplate(ds),
            new DataSourceTransactionManager(ds),
            Clock.fixed(Instant.parse("2026-02-01T00:00:00Z"), ZoneOffset.UTC),
            new Effects());
    var updated = new java.util.concurrent.CountDownLatch(1);
    var commit = new java.util.concurrent.CountDownLatch(1);
    try (var pool = java.util.concurrent.Executors.newFixedThreadPool(2)) {
      var activity =
          pool.submit(
              () ->
                  template.executeWithoutResult(
                      ignored -> {
                        sameTransactionService.recordActivity(
                            "activity", Instant.parse("2026-01-31T00:00:00Z"));
                        updated.countDown();
                        try {
                          commit.await(10, java.util.concurrent.TimeUnit.SECONDS);
                        } catch (InterruptedException e) {
                          throw new RuntimeException(e);
                        }
                      }));
      assertThat(updated.await(10, java.util.concurrent.TimeUnit.SECONDS)).isTrue();
      var scan = pool.submit(() -> service.scan(false));
      commit.countDown();
      activity.get(10, java.util.concurrent.TimeUnit.SECONDS);
      scan.get(10, java.util.concurrent.TimeUnit.SECONDS);
    }
    assertThat(actions.get()).isZero();
    assertThat(service.snapshot("activity").orElseThrow().dueAt())
        .isEqualTo(Instant.parse("2026-02-28T00:00:00Z"));
  }

