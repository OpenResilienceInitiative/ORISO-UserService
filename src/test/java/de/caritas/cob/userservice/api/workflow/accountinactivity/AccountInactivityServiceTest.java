  @Test
  void concurrentCreationKeepsExactlyOneImmutableSnapshot() throws Exception {
    var service = createService(new Effects());
    try (var pool = java.util.concurrent.Executors.newFixedThreadPool(8)) {
      var start = new java.util.concurrent.CountDownLatch(1);
      var futures = new java.util.ArrayList<java.util.concurrent.Future<?>>();
      for (int i = 1; i <= 8; i++) {
        final int months = i;
        futures.add(
            pool.submit(
                () -> {
                  try {
                    start.await();
                  } catch (InterruptedException e) {
                    throw new RuntimeException(e);
                  }
                  service.assignAtCreation(
                      "race", 1L, months, months, Instant.parse("2026-01-01T00:00:00Z"));
                }));
      }
      start.countDown();
      for (var future : futures) future.get(10, java.util.concurrent.TimeUnit.SECONDS);
    }
    var first = service.snapshot("race").orElseThrow();
    service.assignAtCreation("race", 1L, 24, 24, Instant.parse("2026-01-01T00:00:00Z"));
    assertThat(service.snapshot("race").orElseThrow()).isEqualTo(first);
  }

