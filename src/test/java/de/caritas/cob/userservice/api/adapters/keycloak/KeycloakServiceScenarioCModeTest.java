/** Actual public adapter boundary: C never silently falls back to stock native administration. */
class KeycloakServiceScenarioCModeTest {
  private final IdentityClientConfig config = mock(IdentityClientConfig.class);
  private final KeycloakClient nativeClient = mock(KeycloakClient.class);
  private final UsersResource users = mock(UsersResource.class);
  private final UserResource user = mock(UserResource.class);
  private final KeycloakService service =
      new KeycloakService(
          new AuthenticatedUser(),
          mock(UserAccountInputValidator.class),
          config,
          nativeClient,
          mock(KeycloakMapper.class),
          mock(UserHelper.class),
          mock(KeycloakAuthClient.class));

  @BeforeEach
  void realNativeFallbackWouldSucceed() {
    when(config.isFiveActorMode()).thenReturn(true);
    when(nativeClient.getUsersResource()).thenReturn(users);
    when(users.get("target")).thenReturn(user);
    var profile = new UserRepresentation();
    profile.setId("target");
    profile.setUsername("actual-target");
    profile.setEmail("target@example.test");
    profile.setEnabled(true);
    profile.setAttributes(Map.of("locale", List.of("de")));
    when(user.toRepresentation()).thenReturn(profile);
    when(users.search("target@example.test", 0, Integer.MAX_VALUE)).thenReturn(List.of(profile));
    var mappings = mock(RoleMappingResource.class, RETURNS_DEEP_STUBS);
    when(user.roles()).thenReturn(mappings);
    var role = new RoleRepresentation();
    role.setName("user");
    when(mappings.realmLevel().listAll()).thenReturn(List.of(role));
  }

  @Test
  void
      actualProductionRolePortsAreBlockedByThePersistedInactivityClaimAndResumeAfterReactivation() {
    when(config.isFiveActorMode()).thenReturn(false);
    var ds =
        new org.springframework.jdbc.datasource.DriverManagerDataSource(
            "jdbc:h2:mem:actual-role-guard-" + java.util.UUID.randomUUID() + ";DB_CLOSE_DELAY=-1",
            "sa",
            "");
    var jdbc = new org.springframework.jdbc.core.JdbcTemplate(ds);
    jdbc.execute(
        "create table account_inactivity(identity_id varchar(36) primary key,tenant_id bigint,assigned_months int not null,revision bigint not null,last_activity timestamp(6) not null,due_at timestamp(6) not null,status varchar(20) not null,last_error varchar(1000),attempts int default 0 not null)");
    jdbc.execute(
        "create table account_inactivity_journal(journal_id bigint generated by default as identity primary key,identity_id varchar(36),action varchar(30),target varchar(30),outcome varchar(40),created_at timestamp(6))");
    var clock =
        java.time.Clock.fixed(
            java.time.Instant.parse("2026-09-16T10:00:00Z"), java.time.ZoneOffset.UTC);
    var lifecycle =
        new de.caritas.cob.userservice.api.workflow.accountinactivity.AccountInactivityService(
            jdbc,
            new org.springframework.jdbc.datasource.DataSourceTransactionManager(ds),
            clock,
            new de.caritas.cob.userservice.api.workflow.accountinactivity
                .AccountInactivityEffects() {
              public java.util.Set<Role> currentRoles(String id) {
                return java.util.Set.of(Role.CONSULTANT);
              }

              public boolean suspend(String id) {
                return true;
              }

              public boolean reactivate(String id) {
                return true;
              }

              public boolean delete(String id) {
                return false;
              }
            });
    lifecycle.assignAtCreation("target", 1L, 24, 0, clock.instant());
    var realm = mock(org.keycloak.admin.client.resource.RealmResource.class, RETURNS_DEEP_STUBS);
    when(nativeClient.getRealmResource()).thenReturn(realm);
    when(realm.users()).thenReturn(users);
    var assigned = new java.util.LinkedHashSet<String>(List.of("user"));
    var mappings = user.roles().realmLevel();
    when(mappings.listAll())
        .thenAnswer(
            inv ->
                assigned.stream()
                    .map(
                        name -> {
                          var role = new RoleRepresentation();
                          role.setName(name);
                          return role;
                        })
                    .toList());
    for (String name : List.of("user-admin", "consultant")) {
      var role = new RoleRepresentation();
      role.setName(name);
      when(realm.roles().get(name).toRepresentation()).thenReturn(role);
    }
    var writes = new java.util.concurrent.atomic.AtomicInteger();
    doAnswer(
            inv -> {
              assertTrue(
                  org.springframework.transaction.support.TransactionSynchronizationManager
                      .isActualTransactionActive());
              java.util.List<RoleRepresentation> added = inv.getArgument(0);
              added.forEach(role -> assigned.add(role.getName()));
              writes.incrementAndGet();
              return null;
            })
        .when(mappings)
        .add(anyList());
    try (var context =
        new org.springframework.context.annotation.AnnotationConfigApplicationContext()) {
      org.springframework.test.context.support.TestPropertySourceUtils
          .addInlinedPropertiesToEnvironment(
              context, "api.error.keycloakError=fixture-error", "multitenancy.enabled=false");
      context.register(RoleGuardAop.class);
      context.registerBean(KeycloakService.class, () -> service);
      context.registerBean(IdentityClientConfig.class, () -> config);
      context.registerBean(
          de.caritas.cob.userservice.api.workflow.accountinactivity.AccountInactivityService.class,
          () -> lifecycle);
      context.registerBean(
          de.caritas.cob.userservice.api.service.AccountInactivityRoleMutationAspect.class,
          () ->
              new de.caritas.cob.userservice.api.service.AccountInactivityRoleMutationAspect(
                  lifecycle));
      context.refresh();
      var client = context.getBean(de.caritas.cob.userservice.api.port.out.IdentityClient.class);
      var roles =
          context.getBean(de.caritas.cob.userservice.api.port.out.IdentityRoleUpdater.class);
      assertTrue(org.springframework.aop.support.AopUtils.isAopProxy(client));
      assertEquals(
          KeycloakService.class, org.springframework.aop.support.AopUtils.getTargetClass(client));
      client.updateRole("target", de.caritas.cob.userservice.api.config.auth.UserRole.USER_ADMIN);
      assertEquals(1, writes.get());
      assertEquals(java.util.Set.of("user", "user-admin"), assigned);
      assertTrue(lifecycle.suspend("target"));
      assertEquals(
          "SUSPENDED",
          jdbc.queryForObject(
              "select status from account_inactivity where identity_id='target'", String.class));
      assertAll(
          () ->
              assertThrows(
                  org.springframework.web.server.ResponseStatusException.class,
                  () -> roles.ensureRoles("target", List.of("consultant"))),
          () ->
              assertThrows(
                  org.springframework.web.server.ResponseStatusException.class,
                  () -> client.updateRole("target", "consultant")),
          () ->
              assertThrows(
                  org.springframework.web.server.ResponseStatusException.class,
                  () ->
                      client.updateRole(
                          "target",
                          de.caritas.cob.userservice.api.config.auth.UserRole.CONSULTANT)),
          () ->
              assertThrows(
                  org.springframework.web.server.ResponseStatusException.class,
                  () -> client.updateUserRole("target")),
          () ->
              assertThrows(
                  org.springframework.web.server.ResponseStatusException.class,
                  () -> client.removeRoleIfPresent("target", "user-admin")));
      assertEquals(1, writes.get());
      verify(nativeClient, times(1)).getRealmResource();
      assertTrue(lifecycle.reactivate("target"));
      assertEquals(
          "ACTIVE",
          jdbc.queryForObject(
              "select status from account_inactivity where identity_id='target'", String.class));
      roles.ensureRoles("target", List.of("consultant"));
      assertEquals(2, writes.get());
      assertEquals(java.util.Set.of("user", "user-admin", "consultant"), assigned);
    }
  }

  @org.springframework.boot.test.context.TestConfiguration(proxyBeanMethods = false)
  @org.springframework.context.annotation.EnableAspectJAutoProxy
  static class RoleGuardAop {}

  @Test
  void fiveActorsRequiresTheScopedAdapterBeforeRead() {
    assertThrows(IllegalStateException.class, () -> service.findById("target"));
    assertThrows(
        ScopedIdentityCommandRequiredException.class, () -> service.findEnabledById("target"));
    assertThrows(
        ScopedIdentityCommandRequiredException.class,
        () ->
            service.updateProfile(
                "target",
                new de.caritas.cob.userservice.api.port.out.IdentityProfileUpdate(
                    "actual-target", "new@example.test", null, "New", "Name")));
    verifyNoInteractions(nativeClient);
  }

  @Test
  void fiveActorsRequiresTheScopedAdapterBeforePasswordMutation() {
    assertThrows(IllegalStateException.class, () -> service.updatePassword("target", "do-not-log"));
    verify(user, never()).resetPassword(any());
    verifyNoInteractions(nativeClient);
  }

  @Test
  void fiveActorsRequiresTheScopedAdapterBeforeDeactivate() {
    assertThrows(IllegalStateException.class, () -> service.deactivateUser("target"));
    verify(user, never()).update(any());
    verifyNoInteractions(nativeClient);
  }

  @Test
  void fiveActorsRequiresTheScopedAdapterBeforeDeletion() {
    assertThrows(IllegalStateException.class, () -> service.deleteUser("target"));
    verify(user, never()).remove();
    verifyNoInteractions(nativeClient);
  }

  @Test
  void fiveActorsRequiresTheScopedAdapterBeforeEveryOtpRoute() {
    assertAll(
        () ->
            assertThrows(
                IllegalStateException.class, () -> service.getOtpCredential("actual-target")),
        () ->
            assertThrows(
                IllegalStateException.class,
                () -> service.setUpOtpCredential("actual-target", "123456", "do-not-log")),
        () ->
            assertThrows(
                IllegalStateException.class, () -> service.deleteOtpCredential("actual-target")),
        () ->
            assertThrows(
                IllegalStateException.class,
                () -> service.initiateEmailVerification("actual-target", "target@example.test")),
        () ->
            assertThrows(
                IllegalStateException.class,
                () -> service.finishEmailVerification("actual-target", "123456")));
    verifyNoInteractions(nativeClient);
  }

  @Test
  void fiveActorsRollbackPropagatesScopedCommandDemandBeforeNativeCleanup() {
    assertThrows(
        ScopedIdentityCommandRequiredException.class, () -> service.rollbackUser("target"));
    verify(user, never()).remove();
    verifyNoInteractions(nativeClient);
  }

  @Test
  void legacyRollbackRetainsExistingSuccessfulNativeRemoval() {
    when(config.isFiveActorMode()).thenReturn(false);
    assertDoesNotThrow(() -> service.rollbackUser("target"));
    verify(user).remove();
  }

  @Test
  void legacyRollbackRetainsExistingBestEffortNativeFailure() {
    when(config.isFiveActorMode()).thenReturn(false);
    doThrow(new IllegalStateException("Synthetic legacy native failure")).when(user).remove();
    assertDoesNotThrow(() -> service.rollbackUser("target"));
    verify(user).remove();
  }

  @Test
  void fiveActorsChosenPasswordReactivationRequiresScopedOwnerBeforeAnyNativeReadOrRepair() {
    assertThrows(
        ScopedIdentityCommandRequiredException.class,
        () ->
            service.reactivateUser(
                "target", "actual-target", "target@example.test", 7L, "synthetic-chosen-password"));
    verifyNoInteractions(nativeClient);
  }

  @Test
  void fiveActorsEmailOwnerLookupRequiresScopedAuthorityBeforeGenericNativeSearch() {
    assertThrows(
        ScopedIdentityCommandRequiredException.class,
        () -> service.findByEmail("target@example.test"));
    verifyNoInteractions(nativeClient);
  }

  @Test
  void fiveActorsRoleLookupRequiresScopedAuthorityBeforeGenericNativeRoleRead() {
    assertThrows(
        ScopedIdentityCommandRequiredException.class, () -> service.findAllByUserId("target"));
    verifyNoInteractions(nativeClient);
  }

  @Test
  void legacyModeRetainsExistingExactEmailOwnerAndRoleProjections() {
    when(config.isFiveActorMode()).thenReturn(false);
    assertEquals(
        "actual-target", service.findByEmail("target@example.test").orElseThrow().username());
    assertEquals(List.of("user"), service.findAllByUserId("target"));
  }

  @Test
  void legacyModeRetainsExistingProfileProjection() {
    when(config.isFiveActorMode()).thenReturn(false);
    assertEquals(java.util.Optional.of(true), service.findEnabledById("target"));
    assertEquals("target", service.findById("target").orElseThrow().id());
    assertEquals("actual-target", service.findById("target").orElseThrow().username());
  }
}
